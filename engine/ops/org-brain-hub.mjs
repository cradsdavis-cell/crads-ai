#!/usr/bin/env node
// org-brain-hub.mjs — deterministic hub synthesis for an org-brain clone (spec § 3.3).
// Hub-owned files (entities/, decisions/log.md, digest/, .org/manifest.yaml) are REGENERATED
// from members/*/ on every run — idempotent, no merge logic, contradictions surface
// side-by-side instead of being silently resolved. No LLM anywhere in the hub.
//   node org-brain-hub.mjs <clone-dir>     # pull, synthesize, commit, push (best-effort)
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync, unlinkSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const STALE_MS = 36 * 60 * 60 * 1000;   // spec § 3.3: flag members silent > 36h

export function synthesize(cloneDir, { now = new Date() } = {}) {
  const membersDir = path.join(cloneDir, 'members');
  const members = existsSync(membersDir)
    ? readdirSync(membersDir, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort()
    : [];
  // entities/: group member entity pages by filename
  const byEntity = new Map();
  for (const slug of members) {
    const edir = path.join(membersDir, slug, 'entities');
    if (!existsSync(edir)) continue;
    for (const f of readdirSync(edir).filter((f) => f.endsWith('.md'))) {
      if (!byEntity.has(f)) byEntity.set(f, []);
      byEntity.get(f).push({ slug, body: readFileSync(path.join(edir, f), 'utf8').trim() });
    }
  }
  mkdirSync(path.join(cloneDir, 'entities'), { recursive: true });
  // prune stale entity files (not in current byEntity map)
  if (existsSync(path.join(cloneDir, 'entities'))) {
    for (const f of readdirSync(path.join(cloneDir, 'entities'))) {
      if (f.endsWith('.md') && !byEntity.has(f)) {
        try { unlinkSync(path.join(cloneDir, 'entities', f)); } catch {}
      }
    }
  }
  for (const [file, sections] of byEntity) {
    const name = file.replace(/\.md$/, '');
    const out = [`# ${name}`, '', '_Hub-merged view. Sections are per-member; disagreements between sections are real and unresolved._', '']
      .concat(sections.map((s) => `## from ${s.slug}\n\n${s.body}\n`)).join('\n');
    writeFileSync(path.join(cloneDir, 'entities', file), out);
  }
  // decisions/log.md: attributed, exact-line deduped, regenerated wholesale
  const lines = [];
  for (const slug of members) {
    const p = path.join(membersDir, slug, 'decisions.md');
    if (!existsSync(p)) continue;
    for (const l of readFileSync(p, 'utf8').split('\n')) {
      const t = l.trim();
      if (t.startsWith('-')) lines.push(`${t} (${slug})`);
    }
  }
  mkdirSync(path.join(cloneDir, 'decisions'), { recursive: true });
  writeFileSync(path.join(cloneDir, 'decisions', 'log.md'),
    `# Org decisions (hub-merged, attributed)\n\n${[...new Set(lines)].join('\n')}\n`);
  // digest/ + staleness + manifest
  const date = now.toISOString().slice(0, 10);
  const stale = [];
  const stamps = {};
  const digestParts = [`# Org digest — ${date}`, ''];
  for (const slug of members) {
    let stamp = null;
    try { stamp = readFileSync(path.join(membersDir, slug, '.stamp'), 'utf8').trim(); } catch {}
    stamps[slug] = stamp;
    const t = stamp ? Date.parse(stamp) : NaN;
    if (Number.isNaN(t) || now - t > STALE_MS) stale.push(slug);
    let latest = '(no updates published)';
    try {
      const u = readFileSync(path.join(membersDir, slug, 'updates.md'), 'utf8');
      const m = u.match(/^## .*$([\s\S]*?)(?=^## |\n*$(?![\s\S]))/m);
      latest = m ? (m[0].split('\n').slice(0, 12).join('\n')) : latest;
    } catch {}
    digestParts.push(`## ${slug}`, '', latest, '');
  }
  digestParts.push('## Staleness', '', stale.length ? stale.map((s) => `- ${s}: last publish ${stamps[s] || 'never'}`).join('\n') : '- all members fresh (< 36h)', '');
  mkdirSync(path.join(cloneDir, 'digest'), { recursive: true });
  const digestPath = path.join(cloneDir, 'digest', `${date}.md`);
  writeFileSync(digestPath, digestParts.join('\n'));
  mkdirSync(path.join(cloneDir, '.org'), { recursive: true });
  writeFileSync(path.join(cloneDir, '.org', 'manifest.yaml'),
    `# generated by org-brain-hub — member roster + last-publish stamps\nmembers:\n` +
    members.map((s) => `  ${s}: ${stamps[s] ? `"${stamps[s]}"` : 'null'}`).join('\n') + '\n');
  return { entities: byEntity.size, members, stale, digestPath };
}

// ---- CLI ----
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const clone = path.resolve(process.argv[2] || '');
  if (!clone || !existsSync(path.join(clone, '.git'))) { console.error('usage: org-brain-hub.mjs <clone-dir>'); process.exit(1); }
  const g = (...a) => execFileSync('git', ['-C', clone, '-c', 'user.name=hub', '-c', 'user.email=hub@org', ...a], { stdio: 'pipe' });
  try { g('pull', '--rebase', '-q'); } catch { console.error('pull failed — synthesizing from local state'); }
  const r = synthesize(clone);
  g('add', '-A');
  try { g('commit', '-q', '-m', `hub: synthesis ${new Date().toISOString().slice(0, 10)} (${r.members.length} members, ${r.entities} entities${r.stale.length ? `, stale: ${r.stale.join(',')}` : ''})`); }
  catch { console.log('hub: no changes'); process.exit(0); }
  try { g('push', '-q'); console.log(`hub: pushed (${r.members.length} members, ${r.entities} entities, stale: ${r.stale.join(',') || 'none'})`); }
  catch { console.log('hub: committed, push failed (queued)'); }
}
